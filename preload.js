const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('api', {
  library: () => ipcRenderer.invoke('lib:list'),
  importDecks: () => ipcRenderer.invoke('lib:import'),
  deck: id => ipcRenderer.invoke('lib:deck', id),
  removeDeck: id => ipcRenderer.invoke('lib:remove', id),
  search: q => ipcRenderer.invoke('lib:search', q),
  getSettings: () => ipcRenderer.invoke('set:get'),
  saveSettings: s => ipcRenderer.invoke('set:save', s),
  ask: (messages, extra, opts) => ipcRenderer.invoke('ai:ask', messages, extra, opts),
  onStatus: cb => ipcRenderer.on('ai:status', (_, s) => cb(s)),
  extraQuestions: () => ipcRenderer.invoke('q:extra'),
  importQuestions: () => ipcRenderer.invoke('q:import'),
  version: () => ipcRenderer.invoke('app:version'),
  updState: () => ipcRenderer.invoke('upd:state'),
  updCheck: () => ipcRenderer.invoke('upd:check'),
  updDownload: () => ipcRenderer.invoke('upd:download'),
  updInstall: () => ipcRenderer.invoke('upd:install'),
  onUpdate: cb => ipcRenderer.on('upd:status', (_, s) => cb(s)),
  notesList: () => ipcRenderer.invoke('notes:list'),
  notesCategories: () => ipcRenderer.invoke('notes:categories'),
  notesDelete: id => ipcRenderer.invoke('notes:delete', id),
  notesSetCategory: (id, c) => ipcRenderer.invoke('notes:setCategory', id, c),
  notesClear: () => ipcRenderer.invoke('notes:clear'),
  openOriginal: id => ipcRenderer.invoke('orig:open', id),
  linkOriginals: () => ipcRenderer.invoke('orig:linkFolder'),
  openExternal: u => ipcRenderer.invoke('open:ext', u),
});
